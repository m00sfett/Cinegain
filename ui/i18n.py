# Legacy ISO 639-1 code for Indonesian. Accepted for system locales and saved
# configs; the canonical key is "id".
LANGUAGE_ALIASES = {"in": "id"}


def get_system_lang():
    """Detects system language code or defaults to 'en'."""
    try:
        lang_env = os.environ.get("LC_ALL") or os.environ.get("LC_MESSAGES") or os.environ.get("LANG") or ""
        lang_env = lang_env.split(".")[0].replace("_", "-")
        if lang_env in TRANSLATIONS:
            return lang_env
        short = LANGUAGE_ALIASES.get(lang_env.split("-")[0], lang_env.split("-")[0])
        if short == "zh":
            return "zh-CN"
        if short in TRANSLATIONS:
            return short
    except Exception:
        pass
    return "en"


CURRENT_LANG = get_system_lang()


def get_available_languages():
    """Returns mapping of language code to native display name."""
    return dict(LANGUAGE_NAMES)


def get_current_language():
    """Returns the currently active language code."""
    return CURRENT_LANG


def t(key, **kwargs):
    """Translates a string key into the current locale."""
    lang_dict = TRANSLATIONS.get(CURRENT_LANG, TRANSLATIONS["en"])
    text = lang_dict.get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            pass
    return text


def set_language(lang_code):
    global CURRENT_LANG
    lang_code = LANGUAGE_ALIASES.get(lang_code, lang_code)
    if lang_code in TRANSLATIONS:
        CURRENT_LANG = lang_code
        return True
    return False

